"""Writes shared/assessment/cases.txt, the landmark scenarios both measurement engines replay.

The Kotlin engine (android/core/assessment) turns these into shared/assessment/expected.txt, and the web engine
(web/src/features/exercise/assessment) must reproduce that file. Run this only to add or change scenarios, then
regenerate the expected results from Kotlin:

    python scripts/generate_assessment_cases.py
    cd android && UPDATE_SHARED_CASES=1 ./gradlew :core:assessment:test

`--check` only confirms cases.txt matches this generator, as CI does.
"""

import math
import struct
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "shared" / "assessment" / "cases.txt"


def f32(value: float) -> str:
    """The shortest decimal that reads back as the same 32-bit float, so both engines start from identical input."""
    if math.isnan(value):
        return "NaN"
    single = struct.unpack("f", struct.pack("f", value))[0]
    for digits in range(1, 18):
        text = f"{single:.{digits}g}"
        if struct.unpack("f", struct.pack("f", float(text)))[0] == single:
            return text
    return repr(single)


# Left-side landmark positions for each measured joint: the trunk (shoulder 11, hip 23), the chain's proximal point and
# vertex, and the distal point at `angle` degrees from the 0° reference. Right side adds one to every index.
def chain_points(joint: str, angle: float) -> dict[int, tuple[float, float]]:
    s, c = math.sin(math.radians(angle)), math.cos(math.radians(angle))
    if joint == "ELBOW":
        return {11: (.5, .3), 23: (.5, .8), 13: (.5, .5), 15: (.5 + s * .15, .5 + c * .15)}
    if joint == "SHOULDER":
        return {11: (.5, .3), 23: (.5, .8), 13: (.5 + s * .2, .3 + c * .2)}
    if joint == "WRIST":
        return {11: (.5, .2), 23: (.5, .8), 13: (.5, .4), 15: (.5, .6), 19: (.5 + s * .1, .6 + c * .1)}
    if joint == "HIP":
        return {11: (.5, .3), 23: (.5, .6), 25: (.5 + s * .25, .6 + c * .25)}
    if joint == "KNEE":
        return {11: (.5, .15), 23: (.5, .45), 25: (.5, .65), 27: (.5 + s * .2, .65 + c * .2)}
    if joint == "ANKLE":
        return {11: (.5, .1), 23: (.5, .4), 25: (.5, .5), 27: (.5, .7), 31: (.5 + s * .15, .7 + c * .15)}
    raise ValueError(joint)


def person(joint: str, angle: float, side: str = "LEFT", overrides: dict[int, tuple] | None = None, length: int | None = None) -> str:
    shift = 1 if side == "RIGHT" else 0
    points = {index + shift: (x, y, 1.0) for index, (x, y) in chain_points(joint, angle).items()}
    for index, value in (overrides or {}).items():
        points[index] = value
    tokens = ["p"] + ([f"n={length}"] if length is not None else [])
    tokens += [f"{index}:{f32(x)},{f32(y)},{f32(v)}" for index, (x, y, v) in sorted(points.items())]
    return " ".join(tokens)


class Case:
    def __init__(self, lines: list[str], name: str, rules: str = "", width: int = 1000, height: int = 1000):
        self.lines, self.time = lines, 0
        self.joint = next((t.split("=")[1] for t in rules.split() if t.startswith("joint=")), None)
        kind = next((t.split("=")[1] for t in rules.split() if t.startswith("kind=")), "ELBOW_FLEXION")
        self.joint = self.joint or ("SHOULDER" if kind == "SHOULDER_ABDUCTION" else "ELBOW")
        self.side = next((t.split("=")[1] for t in rules.split() if t.startswith("side=")), "LEFT")
        lines += [f"case {name}", f"rules {rules}".rstrip(), f"size {width} {height}"]

    def frame(self, *people: str, step: int = 100) -> "Case":
        self.time += step
        self.lines.append(" ".join([f"frame {self.time}", *people]))
        return self

    def pose(self, *angles: float, step: int = 100) -> "Case":
        for angle in angles:
            self.frame(person(self.joint, angle, self.side), step=step)
        return self

    def at(self, time: int) -> "Case":
        self.time = time
        return self

    def start(self, offset: int = 0) -> "Case":
        self.lines.append(f"start {self.time + offset}")
        return self

    def pause(self) -> "Case":
        self.lines.append(f"pause {self.time}")
        return self

    def restore(self) -> "Case":
        self.lines.append("restore")
        return self

    def ready(self) -> "Case":
        return self.pose(*[10.0] * 6).start()

    def cycle(self, peak: float = 100.0) -> "Case":
        return self.pose(10, 10, 40, 60, peak, peak, peak, 70, 40, 10, 10)


def build() -> list[str]:
    lines = [
        "# Generated by scripts/generate_assessment_cases.py. Edit the generator, not this file.",
        "# Each line is one command; shared/assessment/expected.txt holds the Kotlin engine's answer to each.",
    ]

    # Every built-in and custom joint, on both sides, counts one full repetition.
    joints = [("ELBOW", "kind=ELBOW_FLEXION"), ("SHOULDER", "kind=SHOULDER_ABDUCTION")]
    joints += [(j, f"kind=CUSTOM joint={j} name=Custom") for j in ("WRIST", "HIP", "KNEE", "ANKLE", "ELBOW", "SHOULDER")]
    for joint, rules in joints:
        for side in ("LEFT", "RIGHT"):
            name = f"{joint.lower()}-{side.lower()}-{'custom' if 'CUSTOM' in rules else 'builtin'}"
            Case(lines, name, f"{rules} side={side}").ready().cycle().cycle(60).pose(10, 10)

    # Prescribed (not demo) rules with their own thresholds.
    # The first attempt leaves the target before the 300 ms hold; the second holds and counts.
    Case(lines, "prescribed-thresholds", "demo=false prescription=fixture low=30 high=120 hold=300 min=800").ready().pose(
        10, 40, 70, 100, 125, 125, 90, 60, 30, 10, 10,
        10, 40, 70, 100, 125, 125, 125, 125, 125, 125, 90, 60, 30, 10, 10)

    # Preview counts nothing until measurement starts.
    c = Case(lines, "preview-before-start").pose(*[10.0] * 6).cycle().start().cycle()

    # Start is refused before tracking is ready and more than a second after the last frame.
    c = Case(lines, "start-refused").start().pose(10, 10, 10).start().pose(10, 10, 10).start(1500).start()

    c = Case(lines, "incomplete-range").ready().cycle(60)
    c = Case(lines, "too-fast", "min=10000").ready().cycle()
    c = Case(lines, "hold-required", "hold=500").ready().cycle().pose(10, 40, 60, *[100.0] * 9, 70, 40, 10, 10)
    c = Case(lines, "timeout", "min=100 max=1500").ready().pose(10, 40, 60, 100, 100, 100, *[100.0] * 30, *[10.0] * 6)
    c = Case(lines, "jitter").ready().pose(*[19.0 if i % 2 == 0 else 23.0 for i in range(30)])
    c = Case(lines, "median-spike").ready().pose(10, 60, 10)
    c = Case(lines, "outlier").ready().pose(10, 170, 10, 10)

    c = Case(lines, "tracking-faults").ready().pose(10)
    p = lambda **kw: person("ELBOW", 10, "LEFT", **kw)
    c.frame()  # nobody
    c.frame(p(), p())  # two people
    c.frame(p(overrides={15: (.6, .65, .1)}))  # low visibility
    c.frame(p(overrides={15: (1.1, .65, 1.0)}))  # out of frame
    c.frame(p(overrides={15: (math.nan, .65, 1.0)}))  # not a number
    c.frame(p(length=10))  # too few landmarks
    c.frame(p(overrides={23: (.9, .8, 1.0)}))  # trunk lean
    c.frame(p(overrides={23: (.5, .1, 1.0)}))  # upside-down trunk
    c.frame(p(overrides={13: (.5, .3, 1.0)}))  # elbow on the shoulder
    c.pose(*[10.0] * 6).cycle()

    # Frames just either side of each limit, so a limit moved in one engine changes an answer.
    c = Case(lines, "limits").ready().pose(10)
    for offset in (.1799, .1839):  # trunk lean 19.8° then 20.2°, against the 20° limit
        c.frame(p(overrides={23: (.5 + offset, .8, 1.0)}))
    for gap in (.0051, .0049):  # trunk 5.1 then 4.9 pixels tall, against the 5 pixel minimum
        c.frame(p(overrides={11: (.5, .3, 1.0), 23: (.5, .3 + gap, 1.0)}))
    for visibility in (.7, .6999):  # at and just under the 0.7 confidence
        c.frame(p(overrides={15: (.5260472, .6477212, visibility)}))
    for x in (.98, .9801, .02, .0199):  # the frame edge
        c.frame(p(overrides={15: (x, .6477212, 1.0)}))
    c.pose(*[10.0] * 6).cycle().pose(10, 69, 69)  # 590°/s is allowed
    c.pose(*[69.0] * 3, 40, 10, 10, 10, 10).pose(10, 71)  # 610°/s is an outlier

    # A slow half-degree sweep through every threshold, out and back.
    sweep = [i / 2 for i in range(0, 261)]
    Case(lines, "slow-sweep", "kind=ELBOW_FLEXION side=RIGHT").ready().pose(*sweep, *reversed(sweep))
    Case(lines, "slow-sweep-shoulder", "kind=SHOULDER_ABDUCTION low=30 high=150 hold=0").ready().pose(*sweep[::2], 170, 175, 179.5, *reversed(sweep[::2]))

    c = Case(lines, "lost-at-target").ready().pose(10, 40, 60, 100, 100, 100).frame().pose(*[100.0] * 6, *[10.0] * 6).cycle()
    c = Case(lines, "gap-over-a-second").ready().pose(10, 40, 60, 100, 100, 100)
    c.at(c.time + 2000).pose(*[10.0] * 6).cycle()
    c = Case(lines, "stale-frame").ready().pose(10)
    c.lines.append(f"frame {c.time - 1}")
    c.lines.append(f"frame {c.time}")

    c = Case(lines, "pause-resume").ready().pose(10, 40, 60, 100, 100, 100).pause().pose(*[100.0] * 6).start().pose(*[10.0] * 6).cycle()
    c = Case(lines, "paused-time-excluded").ready().pose(10).pause().pose(*[10.0] * 10).start().pose(10)
    c = Case(lines, "restored-session").ready().cycle().restore().pose(*[10.0] * 6).start().cycle()

    c = Case(lines, "wide-frame", width=1000, height=500).ready().cycle()
    c = Case(lines, "tall-frame", "kind=SHOULDER_ABDUCTION side=RIGHT", width=480, height=640).ready().cycle().pose(5, 45, 135, 175)

    # Pure geometry, the preview transform, diagnostics and the frame policy.
    lines += [
        "case geometry",
        "angle 0.5,0 0,0 0.5,0.5 1000 1000",
        "angle 0.5,0 0,0 0.5,0.5 1000 500",
        "angle 0.5,0.5 0.5,0.5 0.8,0.8 1000 1000",
        "angle 0.2,0.2 0.5,0.5 0.8,0.8 1000 1000",
        "angle 0.5,0.5 0.5,0.5 0.8,0.8 0 1000",
        "map 480 640 1080 1920 false 0.25 0.75",
        "map 480 640 1080 1920 true 0.25 0.75",
        "map 640 480 400 400 true 0 1",
        "diag 300 0:10 33:12 66:40 100:9 133:300",
        "diag 2 0:5 10:7 20:9",
        "policy 0 0", "policy 2 1000", "policy 2 1001", "policy 3 0", "policy 4 2000",
        "slow 59 900", "slow 60 250", "slow 60 251",
    ]
    return lines


def main() -> None:
    text = "\n".join(build()) + "\n"
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            sys.exit(f"{OUT} is out of date. Run python scripts/generate_assessment_cases.py, then regenerate the expected answers.")
        print("shared assessment cases are up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
